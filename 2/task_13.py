# В восточном календаре принят 60-летний цикл, состоящий из 12- летних подциклов,
# обозначаемых названиями цвета: зеленый, красный, желтый, белый и черный.
# В каждом подцикле годы носят названия животных: крысы, коровы, тигра, зайца, дракона,
# змеи, лошади, овцы, обезьяны, курицы, собаки и свиньи. По номеру года вывести его название,
# если 1984 год был началом цикла — годом зеленой крысы.

RESET = "\033[0m"

COLORS = {
    0: ("зеленый", "зеленая", "\033[32m"),
    1: ("красный",  "красная",  "\033[31m"),
    2: ("желтый",   "желтая",   "\033[33m"),
    3: ("белый",    "белая",    "\033[37m"),
    4: ("черный",   "черная",   "\033[30;1m")
}

ANIMALS = {
    0: ("Крыса", 1),
    1: ("Бык", 0),
    2: ("Тигр", 0),
    3: ("Кролик", 0),
    4: ("Дракон", 0),
    5: ("Змея", 1),
    6: ("Лошадь", 1),
    7: ("Коза", 1),
    8: ("Обезьяна", 1),
    9: ("Петух", 0),
    10: ("Собака", 1),
    11: ("Свинья", 1)
}

while True:
    try:
        year = int(input("Введите номер года: "))
        if year > 0: 
            break
        print("Ошибка: год должен быть больше 0.\n")
    except ValueError:
        print("Ошибка: введите целое число.\n")

offset = (year - 1984) % 60

color_data = COLORS[(offset // 2) % 5]
animal_name, gender_idx = ANIMALS[offset % 12]

color_name = color_data[gender_idx]
color_code = color_data[2]

print(f"{color_code}Год {year} — год {color_name} {animal_name}{RESET}")



